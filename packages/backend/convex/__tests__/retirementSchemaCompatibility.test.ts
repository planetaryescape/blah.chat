import { defineSchema, type GenericSchema } from "convex/server";
import { describe, expect, it } from "vitest";
import { BYOD_SCHEMA_VERSION as webVersion } from "../../../../apps/web/src/lib/byod/version";
import bundledSchema from "../../../byod-schema/convex/bundled-schema";
import { BUNDLED_SCHEMA_CONTENT } from "../../../byod-schema/schema-string";
import { BYOD_SCHEMA_VERSION as sharedVersion } from "../../../shared/src/byod/version";
import { convexTest } from "../../__tests__/testSetup";
import { createTestUserData } from "../lib/test/factories";
import schema from "../schema";
import { usageRecordsTable } from "../schema/usage";

describe("retirement usage schema compatibility", () => {
  it("reports the generated schema version consistently to web and backend readers", () => {
    expect(webVersion).toBe(sharedVersion);
    expect(BUNDLED_SCHEMA_CONTENT.split("\n")[0]).toBe(
      `// Auto-generated BYOD schema v${sharedVersion}`,
    );
  });

  const schemas = [
    ["hosted", schema],
    [
      "modular",
      defineSchema({
        users: schema.tables.users,
        usageRecords: usageRecordsTable,
      }),
    ],
    [
      "generated BYOD",
      defineSchema({
        users: schema.tables.users,
        usageRecords: bundledSchema.tables.usageRecords,
      }),
    ],
  ] as const;

  it.each(
    schemas,
  )("keeps legacy and new categories valid in %s", async (_name, definition) => {
    // Each representation supplies its own runtime validator to this shared fixture.
    const t = convexTest<GenericSchema>(definition);
    const records = await t.run(async (ctx) => {
      const userId = await ctx.db.insert("users", createTestUserData());
      for (const feature of [
        "smart_assistant",
        "model_recommendations",
      ] as const) {
        await ctx.db.insert("usageRecords", {
          userId,
          date: "2026-11-03",
          model: "schema-compatibility-fixture",
          feature,
          inputTokens: 10,
          outputTokens: 5,
          cost: 0.01,
          messageCount: 1,
        });
      }
      return ctx.db.query("usageRecords").collect();
    });

    expect(records.map((record) => record.feature)).toEqual(
      expect.arrayContaining(["smart_assistant", "model_recommendations"]),
    );
    expect(records).toHaveLength(2);
    expect(records.reduce((total, record) => total + record.cost, 0)).toBe(
      0.02,
    );
  });
});
